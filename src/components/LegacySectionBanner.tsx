"use client";

import { useState } from "react";
import { AlertTriangle, ArrowRight, Check, CheckCircle2, ChevronRight, Loader2, Sparkles, Users, X } from "lucide-react";
import { motion, AnimatePresence } from "framer-motion";
import { SECTIONS, Section, isAutoGeneratedClassName, generateDefaultClassName } from "@/lib/sections";
import TouchSelect from "@/components/TouchSelect";

interface LegacyInfo {
  hasLegacy: boolean;
  studentsCount: number;
  classesCount: number;
  students: any[];
  classes: any[];
}

interface LegacySectionBannerProps {
  legacyInfo: LegacyInfo | null;
  onSuccess: () => void;
}

export default function LegacySectionBanner({ legacyInfo, onSuccess }: LegacySectionBannerProps) {
  const [modalOpen, setModalOpen] = useState(false);
  const [targetSection, setTargetSection] = useState<Section>("Économie");
  const [mode, setMode] = useState<"all" | "selective">("all");
  const [selectedStudentIds, setSelectedStudentIds] = useState<string[]>([]);
  const [selectedClassIds, setSelectedClassIds] = useState<string[]>([]);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  if (!legacyInfo || !legacyInfo.hasLegacy) return null;

  const openModal = () => {
    setSelectedStudentIds(legacyInfo.students.map((s) => s.id));
    setSelectedClassIds(legacyInfo.classes.map((c) => c.id));
    setTargetSection("Économie");
    setMode("all");
    setError(null);
    setModalOpen(true);
  };

  const handleApply = async () => {
    setSaving(true);
    setError(null);

    try {
      const payload: any = {
        targetSection,
        mode,
      };

      if (mode === "selective") {
        payload.studentIds = selectedStudentIds;
        payload.classIds = selectedClassIds;
      }

      const res = await fetch("/api/sections/legacy", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      const data = await res.json();
      if (!res.ok) {
        setError(data.error || "Une erreur est survenue lors de la mise à jour");
        return;
      }

      setModalOpen(false);
      onSuccess();
    } catch {
      setError("Erreur de connexion");
    } finally {
      setSaving(false);
    }
  };

  const toggleStudent = (id: string) => {
    setSelectedStudentIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  const toggleClass = (id: string) => {
    setSelectedClassIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  const studentsText = `${legacyInfo.studentsCount} élève${legacyInfo.studentsCount > 1 ? "s" : ""}`;
  const classesText = `${legacyInfo.classesCount} classe${legacyInfo.classesCount > 1 ? "s" : ""}`;

  return (
    <>
      {/* BANDEAU VISIBLE D'AVERTISSEMENT */}
      <div className="p-4 sm:p-5 rounded-3xl bg-gradient-to-r from-amber-500/15 via-amber-500/10 to-amber-500/5 dark:from-amber-950/40 dark:via-amber-950/20 dark:to-transparent border border-amber-500/30 flex flex-col sm:flex-row sm:items-center justify-between gap-4 shadow-sm">
        <div className="flex items-start sm:items-center gap-3.5">
          <div className="w-10 h-10 rounded-2xl bg-amber-500/20 text-amber-600 dark:text-amber-400 flex items-center justify-center shrink-0">
            <AlertTriangle className="w-5 h-5" />
          </div>
          <div>
            <h4 className="font-bold text-sm text-slate-900 dark:text-slate-100 flex items-center gap-2">
              <span>Section obsolète détectée</span>
              <span className="px-2 py-0.5 rounded-lg bg-amber-500/20 text-amber-700 dark:text-amber-300 text-[11px] font-bold">
                Sciences
              </span>
            </h4>
            <p className="text-xs text-slate-600 dark:text-slate-400 mt-0.5">
              <span className="font-semibold text-amber-700 dark:text-amber-300">{studentsText}</span> et{" "}
              <span className="font-semibold text-amber-700 dark:text-amber-300">{classesText}</span> ont l'ancienne
              section Sciences. Choisissez une nouvelle section.
            </p>
          </div>
        </div>

        <button
          onClick={openModal}
          className="inline-flex items-center justify-center gap-2 px-5 py-2.5 rounded-xl bg-amber-500 hover:bg-amber-600 text-slate-950 font-bold text-xs shadow-sm transition shrink-0 cursor-pointer"
        >
          <span>Mettre à jour</span>
          <ArrowRight className="w-4 h-4" />
        </button>
      </div>

      {/* MODAL DE MISE À JOUR */}
      <AnimatePresence>
        {modalOpen && (
          <div className="fixed inset-0 z-[70] flex items-center justify-center p-4 bg-black/50 backdrop-blur-sm">
            <motion.div
              initial={{ opacity: 0, scale: 0.95 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.95 }}
              className="w-full max-w-lg p-6 rounded-3xl glass-card bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-2xl max-h-[90dvh] flex flex-col justify-between"
            >
              <div className="overflow-y-auto pr-1 space-y-4">
                {/* En-tête */}
                <div className="flex items-center justify-between pb-3 border-b border-slate-100 dark:border-slate-800">
                  <div className="flex items-center gap-2.5">
                    <div className="w-8 h-8 rounded-xl bg-amber-500/20 text-amber-600 flex items-center justify-center">
                      <Sparkles className="w-4 h-4" />
                    </div>
                    <div>
                      <h3 className="font-bold text-base text-slate-900 dark:text-white">
                        Mise à jour de la section Sciences
                      </h3>
                      <p className="text-xs text-slate-400">
                        Remplacement par une section autorisée
                      </p>
                    </div>
                  </div>
                  <button
                    onClick={() => setModalOpen(false)}
                    className="p-1.5 rounded-lg text-slate-400 hover:text-slate-600"
                  >
                    <X className="w-5 h-5" />
                  </button>
                </div>

                {error && (
                  <div className="p-3 rounded-xl bg-rose-500/10 text-rose-600 text-xs font-semibold">
                    {error}
                  </div>
                )}

                {/* Choix de la nouvelle section */}
                <div>
                  <label className="block text-xs font-bold text-slate-700 dark:text-slate-300 mb-1.5">
                    1. Nouvelle section à appliquer
                  </label>
                  <TouchSelect
                    title="Choisir la nouvelle section"
                    value={targetSection}
                    onChange={(val) => setTargetSection(val as Section)}
                    options={SECTIONS.map((sec) => ({
                      value: sec,
                      label: sec,
                    }))}
                  />
                </div>

                {/* Mode de mise à jour */}
                <div>
                  <label className="block text-xs font-bold text-slate-700 dark:text-slate-300 mb-1.5">
                    2. Modalité d'application
                  </label>
                  <div className="grid grid-cols-2 gap-2">
                    <button
                      type="button"
                      onClick={() => setMode("all")}
                      className={`p-3 rounded-2xl border text-left text-xs font-semibold transition ${
                        mode === "all"
                          ? "bg-indigo-50/80 dark:bg-indigo-950/40 border-indigo-500 text-indigo-700 dark:text-indigo-300"
                          : "bg-slate-50 dark:bg-slate-800/40 border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400"
                      }`}
                    >
                      <div className="font-bold mb-0.5">D'un coup (Recommandé)</div>
                      <div className="text-[11px] opacity-80">
                        Appliquer à toutes les classes et à tous leurs élèves
                      </div>
                    </button>

                    <button
                      type="button"
                      onClick={() => setMode("selective")}
                      className={`p-3 rounded-2xl border text-left text-xs font-semibold transition ${
                        mode === "selective"
                          ? "bg-indigo-50/80 dark:bg-indigo-950/40 border-indigo-500 text-indigo-700 dark:text-indigo-300"
                          : "bg-slate-50 dark:bg-slate-800/40 border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400"
                      }`}
                    >
                      <div className="font-bold mb-0.5">Sélectionner</div>
                      <div className="text-[11px] opacity-80">
                        Choisir élève par élève et classe par classe
                      </div>
                    </button>
                  </div>
                </div>

                {/* Résumé des changements prévus */}
                <div className="space-y-3 pt-2">
                  <div className="text-xs font-bold text-slate-700 dark:text-slate-300">
                    3. Résumé des changements
                  </div>

                  {/* Classes */}
                  {legacyInfo.classes.length > 0 && (
                    <div className="space-y-1.5">
                      <div className="text-[11px] uppercase font-bold tracking-wider text-slate-400">
                        Classes ({legacyInfo.classes.length}) :
                      </div>
                      <div className="space-y-1">
                        {legacyInfo.classes.map((cls) => {
                          const isSelected = selectedClassIds.includes(cls.id);
                          const isAuto = isAutoGeneratedClassName(cls.name, cls.level, cls.section);
                          const futureName = isAuto
                            ? `${cls.level} ${targetSection} (numéro séquentiel auto)`
                            : `${cls.name} (nom personnalisé conservé)`;

                          return (
                            <div
                              key={cls.id}
                              onClick={() => mode === "selective" && toggleClass(cls.id)}
                              className={`p-2.5 rounded-xl border text-xs flex items-center justify-between transition ${
                                mode === "selective" ? "cursor-pointer" : ""
                              } ${
                                isSelected || mode === "all"
                                  ? "bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700"
                                  : "opacity-40 border-dashed border-slate-200 dark:border-slate-800"
                              }`}
                            >
                              <div className="flex items-center gap-2">
                                {mode === "selective" && (
                                  <div
                                    className={`w-4 h-4 rounded border flex items-center justify-center ${
                                      isSelected
                                        ? "bg-indigo-600 border-indigo-600 text-white"
                                        : "border-slate-300 dark:border-slate-600"
                                    }`}
                                  >
                                    {isSelected && <Check className="w-3 h-3" />}
                                  </div>
                                )}
                                <span className="font-semibold text-slate-800 dark:text-slate-200">
                                  {cls.name}
                                </span>
                              </div>
                              <div className="flex items-center gap-1.5 text-[11px] text-indigo-600 dark:text-indigo-400 font-medium">
                                <ArrowRight className="w-3.5 h-3.5" />
                                <span>{futureName}</span>
                              </div>
                            </div>
                          );
                        })}
                      </div>
                    </div>
                  )}

                  {/* Élèves */}
                  {legacyInfo.students.length > 0 && (
                    <div className="space-y-1.5">
                      <div className="text-[11px] uppercase font-bold tracking-wider text-slate-400">
                        Élèves ({legacyInfo.students.length}) :
                      </div>
                      <div className="max-h-40 overflow-y-auto space-y-1 pr-1">
                        {legacyInfo.students.map((st) => {
                          const isSelected = selectedStudentIds.includes(st.id);

                          return (
                            <div
                              key={st.id}
                              onClick={() => mode === "selective" && toggleStudent(st.id)}
                              className={`p-2.5 rounded-xl border text-xs flex items-center justify-between transition ${
                                mode === "selective" ? "cursor-pointer" : ""
                              } ${
                                isSelected || mode === "all"
                                  ? "bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700"
                                  : "opacity-40 border-dashed border-slate-200 dark:border-slate-800"
                              }`}
                            >
                              <div className="flex items-center gap-2">
                                {mode === "selective" && (
                                  <div
                                    className={`w-4 h-4 rounded border flex items-center justify-center ${
                                      isSelected
                                        ? "bg-indigo-600 border-indigo-600 text-white"
                                        : "border-slate-300 dark:border-slate-600"
                                    }`}
                                  >
                                    {isSelected && <Check className="w-3 h-3" />}
                                  </div>
                                )}
                                <span className="font-semibold text-slate-800 dark:text-slate-200">
                                  {st.lastName} {st.firstName}
                                </span>
                                <span className="text-slate-400 text-[11px]">({st.level})</span>
                              </div>
                              <span className="text-[11px] text-emerald-600 dark:text-emerald-400 font-semibold">
                                ➔ {targetSection}
                              </span>
                            </div>
                          );
                        })}
                      </div>
                    </div>
                  )}
                </div>
              </div>

              {/* Boutons d'action */}
              <div className="flex items-center justify-end gap-2 pt-4 border-t border-slate-100 dark:border-slate-800 mt-4">
                <button
                  type="button"
                  onClick={() => setModalOpen(false)}
                  disabled={saving}
                  className="px-4 py-2.5 rounded-xl text-xs font-semibold text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition"
                >
                  Annuler
                </button>
                <button
                  type="button"
                  onClick={handleApply}
                  disabled={saving || (mode === "selective" && selectedStudentIds.length === 0 && selectedClassIds.length === 0)}
                  className="px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 disabled:opacity-50 text-white text-xs font-bold shadow-colored-primary flex items-center gap-2 transition cursor-pointer"
                >
                  {saving ? (
                    <>
                      <Loader2 className="w-3.5 h-3.5 animate-spin" />
                      <span>Mise à jour en cours...</span>
                    </>
                  ) : (
                    <>
                      <CheckCircle2 className="w-4 h-4" />
                      <span>Confirmer et appliquer</span>
                    </>
                  )}
                </button>
              </div>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </>
  );
}
