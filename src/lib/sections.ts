/**
 * Source unique de vérité pour les niveaux scolaires et les sections / filières.
 * 
 * Règles métier :
 * - Niveaux avec section obligatoire : 2ème, 3ème, Bac
 * - Sections autorisées : Informatique, Lettres, Économie
 * - Niveaux sans section : 7ème, 8ème, 9ème, 1ère
 * - Section obsolète / dépréciée : Sciences (conservée en lecture seule pour données existantes)
 */

export const LEVELS = [
  "7ème",
  "8ème",
  "9ème",
  "1ère",
  "2ème",
  "3ème",
  "Bac",
] as const;

export type Level = typeof LEVELS[number];

export const LEVELS_WITH_SECTION = [
  "2ème",
  "3ème",
  "Bac",
] as const;

export type LevelWithSection = typeof LEVELS_WITH_SECTION[number];

export const LEVELS_WITHOUT_SECTION = [
  "7ème",
  "8ème",
  "9ème",
  "1ère",
] as const;

export type LevelWithoutSection = typeof LEVELS_WITHOUT_SECTION[number];

export const SECTIONS = [
  "Informatique",
  "Lettres",
  "Économie",
] as const;

export type Section = typeof SECTIONS[number];

/** Sections obsolètes nécessitant une mise à jour manuelle ou groupée */
export const LEGACY_SECTIONS = [
  "Sciences",
] as const;

export type LegacySection = typeof LEGACY_SECTIONS[number];

/**
 * Vérifie si un niveau scolaire nécessite obligatoirement une section.
 */
export function levelHasSection(level: string | null | undefined): boolean {
  if (!level) return false;
  return (LEVELS_WITH_SECTION as readonly string[]).includes(level.trim());
}

/**
 * Vérifie si une valeur correspond à un niveau valide.
 */
export function isValidLevel(level: string | null | undefined): level is Level {
  if (!level) return false;
  return (LEVELS as readonly string[]).includes(level.trim());
}

/**
 * Vérifie si une valeur correspond à l'une des sections autorisées actuelles.
 */
export function isValidSection(section: string | null | undefined): section is Section {
  if (!section) return false;
  return (SECTIONS as readonly string[]).includes(section.trim());
}

/**
 * Vérifie si une section est une ancienne section supprimée (ex: Sciences).
 */
export function isLegacySection(section: string | null | undefined): boolean {
  if (!section) return false;
  return (LEGACY_SECTIONS as readonly string[]).includes(section.trim());
}

/**
 * Vérifie si un enregistrement (élève ou classe) possède une section à mettre à jour.
 */
export function needsSectionUpdate(
  level: string | null | undefined,
  section: string | null | undefined
): boolean {
  if (!section) {
    // Si le niveau requiert une section mais qu'elle est manquante
    return levelHasSection(level);
  }
  return isLegacySection(section);
}

/**
 * Formate l'affichage combiné du niveau et de la section (ex: "2ème Économie", "1ère", "Bac Informatique").
 */
export function formatLevelAndSection(
  level: string | null | undefined,
  section: string | null | undefined
): string {
  if (!level) return "";
  if (section && section.trim()) {
    return `${level.trim()} ${section.trim()}`;
  }
  return level.trim();
}

/**
 * Génère le nom automatique séquentiel d'une classe.
 * Exemples :
 * - 2ème + Économie + 1 => "2ème Économie classe 1"
 * - 1ère + null + 2     => "1ère classe 2"
 * - Bac + Informatique + 1 => "Bac Informatique classe 1"
 */
export function generateDefaultClassName(
  level: string,
  section: string | null | undefined,
  sequenceNumber: number
): string {
  const cleanLevel = level.trim();
  const sectionPart = section && section.trim() ? `${section.trim()} ` : "";
  return `${cleanLevel} ${sectionPart}classe ${sequenceNumber}`;
}

/**
 * Détermine si le nom d'une classe correspond au motif automatique généré par le système.
 * Permet de savoir si on peut renommer automatiquement la classe lors d'un changement de section
 * sans écraser un nom personnalisé défini par le directeur (ex: "Groupe Excellence", "Salle 4").
 */
export function isAutoGeneratedClassName(
  name: string | null | undefined,
  level: string,
  _section?: string | null | undefined
): boolean {
  if (!name || !name.trim()) return true;
  const trimmed = name.trim();

  // Motif automatique : "<Niveau> [<Section> ]classe <Numéro>"
  // ou "<Niveau> classe <Numéro>"
  const escapedLevel = level.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const pattern = new RegExp(`^${escapedLevel}\\s*(?:.*\\s+)?classe\\s*\\d+$`, "i");
  return pattern.test(trimmed);
}

/**
 * Trouve le prochain numéro disponible pour une classe d'un niveau et d'une section donnés.
 * Si preferredNum est fourni et libre, on l'utilise ; sinon on prend le plus petit entier >= 1 disponible.
 */
export function getNextAvailableClassNumber(
  existingNames: string[],
  level: string,
  section?: string | null,
  preferredNum?: number
): number {
  const cleanLevel = level.trim();
  const escapedLevel = cleanLevel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const sectionPart = section && section.trim() ? `${section.trim().replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s+` : "";
  const pattern = new RegExp(`^${escapedLevel}\\s+${sectionPart}classe\\s*(\\d+)$`, "i");

  const taken = new Set<number>();
  for (const name of existingNames) {
    const match = name.trim().match(pattern);
    if (match) {
      const num = parseInt(match[1], 10);
      if (!isNaN(num)) taken.add(num);
    }
  }

  if (preferredNum && preferredNum > 0 && !taken.has(preferredNum)) {
    return preferredNum;
  }

  let n = 1;
  while (taken.has(n)) {
    n++;
  }
  return n;
}

/**
 * Régénère le nom automatique d'une classe lors d'un changement de section,
 * UNIQUEMENT si le nom n'a pas été personnalisé par le directeur.
 * Si le nouveau nom existe déjà pour la même combinaison, utilise le numéro suivant disponible.
 */
export function resolveClassRenameOnSectionChange(
  currentName: string,
  oldLevel: string,
  oldSection: string | null | undefined,
  newLevel: string,
  newSection: string | null | undefined,
  existingTargetClassNames: string[]
): string {
  // Si le nom était personnalisé, on le conserve intact
  if (!isAutoGeneratedClassName(currentName, oldLevel, oldSection)) {
    return currentName;
  }

  // Tenter d'extraire l'ancien numéro de classe (ex: "3ème Sciences classe 1" => 1)
  const numMatch = currentName.trim().match(/classe\s*(\d+)$/i);
  const preferredNum = numMatch ? parseInt(numMatch[1], 10) : undefined;

  const nextNum = getNextAvailableClassNumber(
    existingTargetClassNames,
    newLevel,
    newSection,
    preferredNum
  );

  return generateDefaultClassName(newLevel, newSection, nextNum);
}

